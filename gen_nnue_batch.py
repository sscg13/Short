#!/usr/bin/env python3
"""Regenerate nnue_opt.asm (the 16-bit NNUE assembly bodies).

The file is fully generated: a fixed prologue (segment, EXTRNs, PUBLICs), the
batched make loops, and the ReLU^2 forward pass. The 64-element bodies are one
instruction line per element, which is tedious and error-prone by hand, so the
per-element templates below are the source of truth; edit this script and run
it rather than patching nnue_opt.asm.

They write the CHILD slot of the ply-indexed accumulator (nn_acc[ply+1][j] =
nn_acc[ply][j] + delta[j], slots are contiguous 256-byte blocks), so undo is a
nn_ply decrement with no restore memcpy. nn_make_move holds both buffer bases
(4 address registers: to, from, src, dst); nn_make_cap needs the three w1 rows
plus dst, so it derives src as dst - 256 via a constant disp16.

Run:  python gen_nnue_batch.py [--check]
        --check: verify the current nnue_opt.asm matches what would be
                 generated (exit 0 = match, 1 = stale), no rewrite.

The generated code is deterministic: the same script + the same templates
always produce the same bytes, so the file can be diffed across edits.
"""

import os
import sys

ASM = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nnue_opt.asm")
N = 64  # hidden width; every element uses byte weight offset +d and acc offset +2d


def _move_body():
    """dst[j] = src[j] + w1[to][j] - w1[from][j]; si=to, bx=from, bp=src, di=dst.

    lodsb streams the to-row and stosw writes the child slot: both advance
    their pointer, and neither address register is needed as a base again.
    That is 1 byte instead of 3 for the weight load (no disp8 EA) and 1 byte
    instead of 4 for the word store (no ES prefix/displacement).
    """
    lines = []
    for d in range(N):
        lines += [
            "        lodsb",                       # w1[to_row][d], SI advances
            "        cbw",
            "        mov     dx, ax",
            "        mov     al, [bx+%d]" % d,   # w1[from_row][d]
            "        cbw",
            "        sub     dx, ax",            # to - from
            "        mov     ax, [bp+%d]" % (2 * d),  # src[j], BP defaults to SS
            "        add     ax, dx",
            "        stosw",                       # dst[j], DI advances
        ]
    return "\n".join(lines)


def _cap_body():
    """dst[j] = src[j] + w1[to][j] - w1[from][j] - w1[cap][j].
    si=to, bx=from, di=cap, bp = dst base (slot nn_ply+1 + persp*128); the src
    (slot nn_ply) is bp - 256, a constant disp16. BP defaults to SS (DGROUP)
    while the weight pointers default to DS, avoiding segment prefixes.

    Only the to-row uses lodsb here: with to/from/cap/slot/dst there are five
    live pointers and only BX/BP/SI/DI can address memory, so DI cannot be
    spent on the advancing stosw destination (CX/DX are not legal bases).
    """
    lines = []
    for d in range(N):
        lines += [
            "        lodsb",                       # w1[to_row][d], SI advances
            "        cbw",
            "        mov     dx, ax",
            "        mov     al, [bx+%d]" % d,   # w1[from_row][d]
            "        cbw",
            "        sub     dx, ax",
            "        mov     al, [di+%d]" % d,  # w1[cap_row][d], default DS
            "        cbw",
            "        sub     dx, ax",            # to - from - cap
            "        mov     ax, [bp-%d]" % (256 - 2 * d),  # src[j], default SS
            "        add     ax, dx",
            "        mov     [bp+%d], ax" % (2 * d),         # dst[j], default SS
        ]
    return "\n".join(lines)


def _shl(reg, times):
    return "\n".join("        shl     %s, 1" % reg for _ in range(times))


def _shr(reg, times):
    return "\n".join("        shr     %s, 1" % reg for _ in range(times))


HEADER = (
    "; =====================================================================\n"
    "; nn_make_move_ - batched PLY-INDEXED NNUE make for a NORMAL move\n"
    "; (quiet or non-capture promo): nn_acc[ply+1][j] = nn_acc[ply][j] +\n"
    "; w1[to_row*64+j] - w1[from_row*64+j] in ONE pass, writing the CHILD slot\n"
    "; of the accumulator stack so undo is a nn_ply decrement (no 256-byte\n"
    "; restore memcpy). src = slot nn_ply (via the _nn_ply global), dst = the\n"
    "; slot 256 bytes after it. Calling convention: FAR, ax=persp, dx=to_row,\n"
    "; bx=from_row. The to-row is streamed with lodsb and the child slot stored\n"
    "; with stosw (SI/DI advance; neither is needed as a base afterwards).\n"
    "; Preserves bx,bp,si,di,ds; clobbers ax,dx,cx,es. Bit-identical\n"
    "; to the in-place RMW (i16 arithmetic mod 2^16).\n"
    "; GENERATED by gen_nnue_batch.py - edit the script, not this block.\n"
    "nn_make_move_ PROC FAR\n"
    "        push    bx\n"
    "        push    bp\n"
    "        push    si\n"
    "        push    di\n"
    "        push    ds\n"
    "        mov     si, dx\n"
    + _shl("si", 6)
    + "\n"
    + _shl("bx", 6)
    + "\n"
    "        mov     di, OFFSET _nn_acc\n"
    "        mov     cx, ss:_nn_ply\n"
    + _shl("cx", 8)
    + "\n"
    "        add     di, cx\n"
    "        mov     bp, di\n"
    "        add     di, 256\n"
    + _shl("ax", 7)
    + "\n"
    "        add     bp, ax\n"
    "        add     di, ax\n"
    "        mov     ax, SEG _nn_w1\n"
    "        mov     ds, ax\n"
    "        add     si, OFFSET _nn_w1\n"
    "        add     bx, OFFSET _nn_w1\n"
    "        mov     ax, ss\n"
    "        mov     es, ax\n"
)

MOVE_FOOTER = (
    "\n"
    "        pop     ds\n"
    "        pop     di\n"
    "        pop     si\n"
    "        pop     bp\n"
    "        pop     bx\n"
    "        retf\n"
    "nn_make_move_ ENDP\n"
)

CAP_HEADER = (
    "\n"
    "; nn_make_cap_ - batched PLY-INDEXED NNUE make for a CAPTURE or EP:\n"
    "; nn_acc[ply+1][j] = nn_acc[ply][j] + w1[to_row*64+j] - w1[from_row*64+j]\n"
    "; - w1[cap_row*64+j] in ONE pass into the CHILD slot. The three w1 rows use\n"
    "; si/bx/di and dst uses bp, so the src (slot nn_ply) is read as bp - 256\n"
    "; (a constant disp16 - the child slot is always 256 bytes past its parent).\n"
    "; BP defaults to SS (DGROUP); all three weight pointers default to DS.\n"
    "; The to-row uses lodsb; the destination keeps the direct SS store because\n"
    "; the five live pointers leave no address register for an advancing DI.\n"
    "; Calling convention: FAR, ax=persp, dx=to_row, bx=from_row, cx=cap_row.\n"
    "; Preserves bx,bp,si,di,ds; clobbers ax,dx,cx,es.\n"
    "; GENERATED by gen_nnue_batch.py - edit the script, not this block.\n"
    "nn_make_cap_ PROC FAR\n"
    "        push    bx\n"
    "        push    bp\n"
    "        push    si\n"
    "        push    di\n"
    "        push    ds\n"
    "        mov     si, dx\n"
    + _shl("si", 6)
    + "\n"
    + _shl("bx", 6)
    + "\n"
    "        mov     di, cx\n"
    + _shl("di", 6)
    + "\n"
    "        mov     bp, OFFSET _nn_acc\n"
    "        mov     cx, ss:_nn_ply\n"
    + _shl("cx", 8)
    + "\n"
    "        add     bp, cx\n"
    "        add     bp, 256\n"
    + _shl("ax", 7)
    + "\n"
    "        add     bp, ax\n"
    "        mov     ax, SEG _nn_w1\n"
    "        mov     ds, ax\n"
    "        add     si, OFFSET _nn_w1\n"
    "        add     bx, OFFSET _nn_w1\n"
    "        add     di, OFFSET _nn_w1\n"
)

CAP_FOOTER = (
    "\n"
    "        pop     ds\n"
    "        pop     di\n"
    "        pop     si\n"
    "        pop     bp\n"
    "        pop     bx\n"
    "        retf\n"
    "nn_make_cap_ ENDP\n"
)


def generate():
    return (HEADER + _move_body() + MOVE_FOOTER + CAP_HEADER
            + _cap_body() + CAP_FOOTER)


# ---------------------------------------------------------------------------
# nn_fwd_eval_ - the ReLU^2 forward pass, generated for the same reason the
# make/cap loops are: 64 slots x 2 perspectives of a mechanical clamp-load-
# accumulate body. act = clamp(acc, 0, 255); nonpositive terms contribute zero
# and skip the table load and accumulation entirely.
# (the old symmetric clamp's shift-only +/-128 fast path does not exist).
# ---------------------------------------------------------------------------

def _fwd_body():
    """per-slot stm+nstm blocks: acc -> act = clamp(acc,0,255) -> table load.
    bx=stm acc base, bp=nstm acc base; di = 2*act; fwd[0][j] base = j*512,
    fwd[1][j] base = 32768 + j*512 (the shared [2][64][256] far array)."""
    lines = []
    for j in range(N):
        lines.append("; ---- slot %d ----" % j)
        for reg, tag, base in (("bx", "0", 512 * j), ("bp", "1", 32768 + 512 * j)):
            lines += [
                "        mov     ax, ss:[%s+%d]" % (reg, 2 * j),
                "        test    ax, ax",
                "        jle     V2DN%s_%d" % (tag, j),
                "        cmp     ax, 255",
                "        jle     V2OK%s_%d" % (tag, j),
                "        mov     ax, 255",
                "V2OK%s_%d:" % (tag, j),
                "        add     ax, ax",
                "        mov     di, ax",
                "        mov     ax, [di+%d]" % base,
                "        cwd",
                "        add     si, ax",
                "        adc     cx, dx",
                "V2DN%s_%d:" % (tag, j),
            ]
    return "\n".join(lines)


FWD_HEADER = (
    "\n; =====================================================================\n"
    "; nn_fwd_eval_ - NNUE forward pass (ReLU^2) via per-slot product tables:\n"
    "; act = clamp(acc, 0, 255) and fwd[p][j][act] = (act^2 * w2) >>\n"
    "; NNUE_ACT2_SHIFT (9) (the squared product is pre-shifted so every entry\n"
    "; fits i16 - max 255^2*127>>9 = 16129). Nonpositive terms skip all work.\n"
    "; Table layout is the shared far array fwd[2][64][256]: fwd[0][j]\n"
    "; base = j*512, fwd[1][j] base = 32768 + j*512 (persp 1 starts at +32768).\n"
    "; si:cx = the 32-bit accumulator seeded from the bias; the finish shifts it\n"
    "; right 5 (1.0 = 256 cp). Calling convention: FAR, ax=side.\n"
    "; Preserves bx,bp,si,di,ds; clobbers ax,dx,cx,es.\n"
    "; GENERATED by gen_nnue_batch.py - edit the script, not this block.\n"
    "nn_fwd_eval_ PROC FAR\n"
    "        push    bp\n"
    "        push    bx\n"
    "        push    si\n"
    "        push    di\n"
    "        push    ds\n"
    "        mov     bx, OFFSET _nn_acc\n"
    "        mov     cx, ss:_nn_ply\n"
    + _shl("cx", 8)
    + "\n"
    "        add     bx, cx\n"
    "        mov     dx, ax\n"
    + _shl("dx", 7)
    + "\n"
    "        mov     bp, bx\n"
    "        add     bp, 128\n"
    "        sub     bp, dx\n"
    "        add     bx, dx\n"
    "        mov     ax, SEG _nn_fwd\n"
    "        mov     ds, ax\n"
    "        mov     ax, ss:_nn_bias\n"
    "        cwd\n"
    "        mov     si, ax\n"
    "        mov     cx, dx\n"
)

FWD_FINISH = (
    "\n; --- finish: (si:cx >> NNUE_SCALE_SHIFT) low word (score from stm's POV) ---\n"
    "        mov     ax, cx\n"
    + _shl("ax", 11)
    + "\n"
    "        mov     dx, si\n"
    + _shr("dx", 5)
    + "\n"
    "        or      ax, dx\n"
    "        pop     ds\n"
    "        pop     di\n"
    "        pop     si\n"
    "        pop     bx\n"
    "        pop     bp\n"
    "        retf\n"
    "nn_fwd_eval_ ENDP\n"
)


def generate_fwd():
    return FWD_HEADER + _fwd_body() + FWD_FINISH


PROLOG = (
    "; nnue_opt.asm - hand-unrolled 64-element NNUE batch and forward loops\n"
    "; (8088 target). GENERATED by gen_nnue_batch.py - edit the script, not this file.\n"
    ";\n"
    "; nn_make_move_ / nn_make_cap_ replace the compiler's 64-iteration apply loop -\n"
    "; which reloads DS to the far weight segment on EVERY element, increments two\n"
    "; pointers, and pays a backward-branch prefetch-queue flush (the tight-loop\n"
    "; refetch) each iteration - with fully unrolled straight-line code that folds\n"
    "; the parent-slot copy and the weight deltas into ONE pass writing the child\n"
    "; slot. Constant disp8/disp16 addressing: no loop, no pointer bumps.\n"
    ";\n"
    "; nn_fwd_eval_ is the ReLU^2 forward pass over the pre-shifted product tables.\n"
    ";\n"
    "; Calling convention (OpenWatcom 16-bit, large model): FAR procs; arguments in\n"
    "; the registers named in each routine's own header; each preserves the state\n"
    "; it documents and clobbers ax, dx, cx, es.\n"
    ";\n"
    "        .8086\n"
    "        NAME    nnue_opt\n"
    "\n"
    "_TEXT   SEGMENT BYTE PUBLIC USE16 'CODE'\n"
    "        ASSUME  CS:_TEXT\n"
    "\n"
    "        EXTRN   _nn_w1:BYTE\n"
    "        EXTRN   _nn_acc:WORD\n"
    "        EXTRN   _nn_ply:WORD\n"
    "        EXTRN   _nn_fwd:WORD\n"
    "        EXTRN   _nn_w2:BYTE\n"
    "        EXTRN   _nn_bias:WORD\n"
    "\n"
    "        PUBLIC  nn_make_move_\n"
    "        PUBLIC  nn_make_cap_\n"
    "        PUBLIC  nn_fwd_eval_\n"
)


def generate():
    return (HEADER + _move_body() + MOVE_FOOTER + CAP_HEADER
            + _cap_body() + CAP_FOOTER)


def main():
    new_content = (PROLOG + "\n" + generate()
                   + "\n; =====================================================================\n"
                   + generate_fwd()
                   + "\n_TEXT   ENDS\n        END\n")

    with open(ASM, "r") as f:
        content = f.read()

    if "--check" in sys.argv:
        if new_content == content:
            print("nnue_opt.asm is up to date.")
            return 0
        print("nnue_opt.asm is STALE - run gen_nnue_batch.py to regenerate.")
        return 1

    with open(ASM, "w") as f:
        f.write(new_content)
    print("Regenerated %s" % ASM)
    return 0


if __name__ == "__main__":
    sys.exit(main())
